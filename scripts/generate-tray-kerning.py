"""Generate the Geist kerning table the tray applies by hand.

GDI+ reads only the legacy kern table; Geist keeps its kerning in GPOS. Every
Latin run therefore measures ~2% wide in the tray, which shifts word positions
and changes where paragraphs wrap. Measured against Chrome, applying these pairs
makes the widths match to 0.01px.

The table is restricted to the characters the panel can draw (printable ASCII
plus a few symbols): ~3000 pairs per weight. Each weight is emitted as a base64
blob of big-endian (key, value) short pairs, keyed by (c1 << 8) | c2.
"""

import base64
import struct
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
MEDIA = ROOT / ".next" / "static" / "media"
OUT = ROOT / "tray" / "Kerning.cs"
WEIGHTS = (400, 500, 600, 700)
# Only Latin-1 characters: the char -> index map is a 256-entry table, so a
# code point above 0xFF could not be looked up at runtime anyway. The symbols
# the panel does draw (¥ · ×) are all below it.
CHARS = set(chr(c) for c in range(0x20, 0x7F)) | set("¥·×")
# A dense index so a character pair packs into one 16-bit key.
ALPHABET = "".join(chr(c) for c in range(0x20, 0x7F)) + "¥·×"
def find_latin_subset():
    best = None
    for path in sorted(MEDIA.glob("*.woff2")):
        font = TTFont(path, lazy=True)
        family = font["name"].getDebugName(1) or ""
        cmap = font.getBestCmap() or {}
        ok = ord("O") in cmap and ord("A") in cmap and ord("z") in cmap
        score = font["maxp"].numGlyphs
        font.close()
        if family == "Geist" and ok and (best is None or score > best[1]):
            best = (path, score)
    return best[0] if best else None


def kern_pairs(font):
    gpos = font["GPOS"].table
    wanted = []
    for rec in gpos.FeatureList.FeatureRecord:
        if rec.FeatureTag in ("kern", "dist"):
            wanted.extend(rec.Feature.LookupListIndex)
    pairs = {}
    for idx in set(wanted):
        for sub in gpos.LookupList.Lookup[idx].SubTable:
            if sub.LookupType != 2:
                continue
            if getattr(sub, "Format", None) == 1:
                for i, g1 in enumerate(sub.Coverage.glyphs):
                    for pvr in sub.PairSet[i].PairValueRecord:
                        pairs[(g1, pvr.SecondGlyph)] = pvr.Value1.XAdvance
            elif getattr(sub, "Format", None) == 2:
                c1 = sub.ClassDef1.classDefs
                c2 = sub.ClassDef2.classDefs
                for g1 in sub.Coverage.glyphs:
                    k1 = c1.get(g1, 0)
                    for g2, k2 in c2.items():
                        rec = sub.Class1Record[k1].Class2Record[k2]
                        pairs[(g1, g2)] = rec.Value1.XAdvance
    return pairs


def encode(font, pairs):
    cmap = font.getBestCmap()
    rev = {}
    for cp, g in sorted(cmap.items()):
        if chr(cp) in CHARS and g not in rev:
            rev[g] = cp
    rows = []
    for (g1, g2), v in pairs.items():
        a, b = rev.get(g1), rev.get(g2)
        if a is None or b is None or not v:
            continue
        # Index into the alphabet rather than using the code point directly: the
        # symbol characters (arrow, yen, ellipsis) are above 0xFF and would
        # overflow the packed 16-bit key.
        rows.append(((ALPHABET.index(chr(a)) << 8) | ALPHABET.index(chr(b)),
                     max(-32768, min(32767, v))))
    rows.sort()
    return rows, b"".join(struct.pack(">hh", k, v) for k, v in rows)


HEAD = '''// <auto-generated>
//     Generated by scripts/generate-tray-kerning.py from the Geist subsets that
//     next/font bundles. Do not edit by hand.
//
//     GDI+ only reads the legacy kern table and Geist keeps its kerning in GPOS,
//     so every Latin run measured about 2% wide and paragraphs wrapped in the
//     wrong place. These are the pair adjustments in font units per 1000 em,
//     keyed by (char1 << 8) | char2.
// </auto-generated>

using System;
using System.Collections.Generic;

namespace RouterMonitorTray
{
    internal static class Kerning
    {
        /// <summary>
        /// Set false by the --no-kern diagnostic. Kerning makes the tray's run
        /// widths match the browser exactly; this exists to A/B that in a render.
        /// </summary>
        public static bool Enabled = true;

        private const float UnitsPerEm = 1000f;

'''

TAIL = '''
        private static readonly Dictionary<int, Dictionary<int, int>> Tables =
            new Dictionary<int, Dictionary<int, int>>();

        private static readonly int[] Weights = new int[] { 400, 500, 600, 700 };
        private static readonly string[] Blobs = new string[] { W400, W500, W600, W700 };

        /// <summary>
        /// Maps a character to its index in the table's alphabet, or -1 when it is
        /// not in it (anything above Latin-1, plus the unused C0 controls).
        /// </summary>
        private static readonly sbyte[] Index = BuildIndex();

        private static sbyte[] BuildIndex()
        {
            sbyte[] map = new sbyte[256];
            for (int i = 0; i < map.Length; i++)
            {
                map[i] = -1;
            }
            byte[] packed = Convert.FromBase64String(IndexBlob);
            for (int i = 0; i + 2 < packed.Length; i += 3)
            {
                map[(packed[i] << 8) | packed[i + 1]] = (sbyte)packed[i + 2];
            }
            return map;
        }

        /// <summary>
        /// The adjustment between two characters at a CSS weight, in font units per
        /// 1000 em. Zero when the pair is not kerned or either is outside the
        /// alphabet.
        /// </summary>
        public static int Pair(int weight, char first, char second)
        {
            if (first > 0xFF || second > 0xFF)
            {
                return 0;
            }
            int a = Index[first];
            int b = Index[second];
            if (a < 0 || b < 0)
            {
                return 0;
            }
            int index = 0;
            for (int i = 0; i < Weights.Length; i++)
            {
                if (weight >= Weights[i])
                {
                    index = i;
                }
            }
            Dictionary<int, int> table = Table(Weights[index], Blobs[index]);
            int value;
            return table.TryGetValue((a << 8) | b, out value) ? value : 0;
        }

        /// <summary>The adjustment in pixels at a font size.</summary>
        public static float Pixels(int weight, char first, char second, float px)
        {
            int value = Pair(weight, first, second);
            return value == 0 ? 0f : value / UnitsPerEm * px;
        }

        private static Dictionary<int, int> Table(int weight, string blob)
        {
            Dictionary<int, int> table;
            if (Tables.TryGetValue(weight, out table))
            {
                return table;
            }
            byte[] bytes = Convert.FromBase64String(blob);
            table = new Dictionary<int, int>(bytes.Length / 4);
            for (int i = 0; i + 3 < bytes.Length; i += 4)
            {
                int key = (bytes[i] << 8) | bytes[i + 1];
                short value = (short)((bytes[i + 2] << 8) | bytes[i + 3]);
                table[key] = value;
            }
            Tables[weight] = table;
            return table;
        }
    }
}
'''


def main():
    source = find_latin_subset()
    if source is None:
        raise SystemExit("no Geist latin subset under .next/static/media")

    var = TTFont(source)
    # A char -> alphabet index map, packed as (char, index) byte pairs. Every
    # character the panel can draw is below 0x100, so a 256-entry table suffices.
    index_blob = base64.b64encode(
        b"".join(struct.pack(">HB", ord(ch), i) for i, ch in enumerate(ALPHABET))
    ).decode("ascii")


    parts = [HEAD]
    for wght in WEIGHTS:
        font = instancer.instantiateVariableFont(var, {"wght": wght}, inplace=False)
        rows, blob = encode(font, kern_pairs(font))
        b64 = base64.b64encode(blob).decode("ascii")
        font.close()
        parts.append("        /// <summary>%d kerned pairs at weight %d.</summary>\n" % (len(rows), wght))
        parts.append("        private const string W%d =\n" % wght)
        for i in range(0, len(b64), 100):
            parts.append('            "%s" +\n' % b64[i:i + 100])
        parts.append('            "";\n\n')
    parts.append('        private const string IndexBlob =\n')
    for i in range(0, len(index_blob), 100):
        parts.append('            "%s" +\n' % index_blob[i:i + 100])
    parts.append('            "";\n')
    parts.append(TAIL)
    OUT.write_text("".join(parts).replace("\n", "\r\n"), encoding="utf-8")
    print("wrote %s (%d bytes)" % (OUT.name, OUT.stat().st_size))


if __name__ == "__main__":
    main()
